import type { Backdrop, Particles, Story } from '../types';
import { ART_STYLE as A, sc } from './nayanar';

/**
 * Nayanmar retold from the prose digest printed with Sekkizhar's Periya Puranam (the edition in
 * the supplied PDF, "பெரியபுராணம்"). Only events stated in that digest or its verses are used;
 * the wording is Divine Life's own. Each story keeps to what the source says and nothing more.
 */
type SceneSpec = [id: string, title: string, backdrop: Backdrop, lines: string[], art: string, particles?: Particles];

export type Spec = {
  id: string;
  n: number;
  name: string;
  title: string;
  subtitle: string;
  pages: string;
  sourceReviewed?: boolean;
  source?: string;
  scenes: SceneSpec[];
  essence: string;
  words: { w: string; m: string }[];
  meaning: string;
  wisdom: [string, string, string, string];
  reflection: { question: string; options: string[] };
  practice: { label: string; detail: string; route: '/practice/dhyanam' | '/practice/japa'; minutes: number };
  ask: string[];
};

const NOTE = 'இது Divine Life எழுதிய கதைச் சாரம்; தேவாரப் பாடலோ மூலப் பாடலோ அல்ல.';

export function nayanar(s: Spec): Story {
  return {
    id: s.id,
    sourceReviewed: s.sourceReviewed ?? false,
    title: s.title,
    subtitle: s.subtitle,
    purana: `பெரிய புராணம் · நாயன்மார் ${s.n}`,
    source: s.source ?? `மூலம்: சேக்கிழார், "பெரிய புராணம்" — ${s.name} புராணம் (PDF பக்கங்கள் ${s.pages}). உரை Divine Life-இன் சொந்த மறுகூறல்; மூல ஒப்பீடு நிலுவையில் உள்ளது.`,
    minutes: 3,
    scenes: s.scenes.map(([id, title, backdrop, lines, art, particles]) => sc(id, title, backdrop, lines, A + art, particles ?? 'dust')),
    verse: {
      ref: 'கதையின் சாரம் (Divine Life)',
      devanagari: '',
      tamilScript: s.essence,
      words: s.words,
      meaning: s.meaning,
      note: NOTE,
    },
    wisdom: [
      { heading: 'எப்படி வாழ்ந்தார்', body: s.wisdom[0] },
      { heading: 'எப்படி வழிபட்டார்', body: s.wisdom[1] },
      { heading: 'ஒழுக்கம்', body: s.wisdom[2] },
      { heading: 'நமக்கான பாடம்', body: s.wisdom[3] },
    ],
    reflection: s.reflection,
    practice: s.practice,
    askSuggestions: s.ask,
  };
}

