// Scans assets/audio/story/<story>/<scene>.(m4a|mp3|wav|aac) and rewrites src/content/audioManifest.ts.
// Run it after adding or replacing recordings.  (.ogg from WhatsApp will not play on iPhone — convert:
//   ffmpeg -i in.ogg -c:a aac -b:a 96k out.m4a )
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './_stories.mjs';

const dir = path.join(ROOT, 'assets/audio/story');
const lines = [];
const warn = [];
if (fs.existsSync(dir))
  for (const sd of fs.readdirSync(dir).sort())
    for (const f of fs.readdirSync(path.join(dir, sd)).sort()) {
      const m = f.match(/^(.+)\.(m4a|mp3|wav|aac|ogg)$/i);
      if (!m) continue;
      if (m[2].toLowerCase() === 'ogg') warn.push(`${sd}/${f} is .ogg — convert to .m4a so iPhones can play it`);
      lines.push(`  '${sd}/${m[1]}': require('@/assets/audio/story/${sd}/${f}'),`);
    }
fs.writeFileSync(
  path.join(ROOT, 'src/content/audioManifest.ts'),
  `// AUTO-GENERATED by tools/build_audio_manifest.mjs — do not edit by hand.
// Maps "<storyId>/<sceneId>" to the narrator's own recording of that scene.
export const SCENE_CLIPS: Record<string, number> = {
${lines.join('\n')}
};

export function sceneClip(storyId: string, sceneId: string): number | undefined {
  return SCENE_CLIPS[\`\${storyId}/\${sceneId}\`];
}
`,
);
console.log(lines.length, 'scene recordings registered');
warn.forEach((w) => console.log('!', w));
